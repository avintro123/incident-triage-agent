# ==============================================================================
# Step 11: Node 2 — The Self-Correcting Retrieval Grader & Query Rewriter
# File: backend/src/backend/core/nodes/grader.py
#
# FOR BEGINNERS:
# Why is this node called "Self-Correcting"?
# In basic AI chatbots, if search returns garbage, the AI blindly guesses anyway.
#
# Node 2 acts like a Quality Inspector:
# 1. Reads the retrieved cards before the AI starts writing.
# 2. Checks: "Do these cards actually contain the fix for this incident?"
# 3. If YES: Passes the case to the Doctor.
# 4. If NO: Rewrites the search query with better terms and loops back to search again!
# ==============================================================================

import os
import re
import logging
from typing import Optional
from pydantic import BaseModel, Field

# Import our Case File blueprint from Step 9
from backend.core.state import AgentState

logger = logging.getLogger(__name__)


class GradeResult(BaseModel):
    """
    The structured report card generated by the Grader.
    """
    is_relevant: bool = Field(
        description="True if the retrieved documents contain actionable technical solutions"
    )
    confidence_score: float = Field(
        description="Confidence score between 0.0 and 1.0"
    )
    rewritten_query: Optional[str] = Field(
        default=None,
        description="If is_relevant is False, a reformulated search query with better keywords"
    )
    reasoning: str = Field(
        description="Brief explanation of why the documents passed or failed the grade"
    )


class RetrievalGraderNode:
    """
    Node 2 in the LangGraph State Machine:
    The Quality Inspector that grades evidence and loops back to rewrite queries
    if the search results are poor.
    """

    def __init__(
        self,
        google_api_key: Optional[str] = None,
        model_name: str = "gemini-2.5-flash",
        max_retries: int = 3
    ):
        self.google_api_key = google_api_key or os.getenv("GOOGLE_API_KEY", "") or os.getenv("GEMINI_API_KEY", "")
        self.model_name = model_name
        self.max_retries = max_retries
        self.llm = None

        if self.google_api_key:
            try:
                from langchain_google_genai import ChatGoogleGenerativeAI
                self.llm = ChatGoogleGenerativeAI(
                    model=self.model_name,
                    google_api_key=self.google_api_key,
                    temperature=0.0
                )
            except Exception as e:
                logger.warning(f"Could not load Gemini in RetrievalGraderNode: {e}")

    def __call__(self, state: AgentState) -> AgentState:
        """
        Executes Node 2:
        Inspects state.retrieved_docs against state.incident_report.
        """
        logger.info(f"Node 2 (Grader): Grading {len(state.retrieved_docs)} cards. (Retry count: {state.search_retry_count})")

        # 1. Run the evaluation
        grade = self._evaluate_evidence(state)

        # 2. Check the verdict
        if grade.is_relevant:
            # PASS: Evidence is good, move forward!
            state.grader_verdict = "pass"
            state.step_history.append(
                f"Grader: PASSED (Confidence: {grade.confidence_score * 100:.0f}%) - {grade.reasoning}"
            )
        else:
            # FAIL: Evidence is poor. Check our loop guard!
            if state.search_retry_count < self.max_retries:
                # Loop back: Increment retry counter and replace sub-queries with the rewritten query
                state.search_retry_count += 1
                state.grader_verdict = "rewrite_query"
                new_query = grade.rewritten_query or f"{state.incident_report} troubleshooting runbook"
                state.sub_queries = [new_query]
                state.step_history.append(
                    f"Grader: REJECTED evidence (Attempt {state.search_retry_count}/{self.max_retries}). "
                    f"Rewrote query to: '{new_query}'"
                )
            else:
                # Max retries reached: Stop looping to prevent an infinite loop, and proceed with best effort
                state.grader_verdict = "pass"
                state.step_history.append(
                    f"Grader: Max retries ({self.max_retries}) reached. Proceeding with best available evidence."
                )

        return state

    def _evaluate_evidence(self, state: AgentState) -> GradeResult:
        """
        Asks Gemini to inspect the cards, or uses our smart rule-based fallback
        for offline unit tests.
        """
        if not state.retrieved_docs:
            return GradeResult(
                is_relevant=False,
                confidence_score=0.0,
                rewritten_query=self._generate_fallback_query(state.incident_report),
                reasoning="Zero documents were retrieved."
            )

        if self.llm:
            try:
                # Combine cards into a clean summary for Gemini to review
                docs_text = "\n---\n".join([
                    f"Source: {c.source} | Section: {c.section_title}\nContent: {c.content[:400]}"
                    for c in state.retrieved_docs
                ])

                structured_llm = self.llm.with_structured_output(GradeResult)
                prompt = (
                    "You are a strict QA auditor for Site Reliability Engineering.\n"
                    "Grade whether the following retrieved documentation cards contain the specific "
                    "root cause or recovery steps to fix the incident report.\n\n"
                    f"Incident Report: {state.incident_report}\n\n"
                    f"Retrieved Documents:\n{docs_text}\n\n"
                    "If the documents do NOT contain actionable steps to resolve the issue, mark is_relevant=False "
                    "and provide a rewritten_query with better search keywords."
                )
                return structured_llm.invoke(prompt)
            except Exception as e:
                logger.warning(f"Gemini grading failed ({e}), using local rule-based grader.")

        # --- Smart Offline Fallback (For unit tests) ---
        return self._local_rule_based_grader(state)

    def _local_rule_based_grader(self, state: AgentState) -> GradeResult:
        """
        Rule-based grader for local unit tests without needing an API key.
        Checks for technical keywords, commands, and error codes.
        """
        report_lower = state.incident_report.lower()
        combined_docs = " ".join([c.content.lower() + " " + (c.section_title or "").lower() for c in state.retrieved_docs])

        # Extract technical tokens from the report
        error_tokens = re.findall(r"[a-z0-9_\-]{4,}", report_lower)
        matches = [t for t in error_tokens if t in combined_docs]

        # If at least 30% of key tokens or a diagnostic command is found, pass!
        has_commands = any(cmd in combined_docs for cmd in ["redis-cli", "select", "config set", "systemctl", "curl"])
        has_overlap = len(matches) >= max(1, len(error_tokens) // 3)

        if has_commands or has_overlap:
            return GradeResult(
                is_relevant=True,
                confidence_score=0.88,
                reasoning=f"Found key technical overlap ({len(matches)} matching terms) and diagnostic steps."
            )
        else:
            return GradeResult(
                is_relevant=False,
                confidence_score=0.20,
                rewritten_query=self._generate_fallback_query(state.incident_report),
                reasoning="Retrieved cards do not contain relevant diagnostic commands or error matches."
            )

    def _generate_fallback_query(self, report: str) -> str:
        """Generates alternative search keywords when search fails."""
        words = re.findall(r"[A-Za-z0-9_\-]+", report)
        return " ".join(words[:4]) + " error recovery runbook"
