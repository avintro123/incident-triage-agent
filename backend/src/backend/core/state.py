# File: backend/src/backend/core/state.py
#
# FOR BEGINNERS:
# In LangGraph, the agent is like a team of detectives solving a case.
# They don't shout across the room; they pass around a single "Case File" (Clipboard).
#
# Every node in the graph:
# 1. Opens this clipboard
# 2. Reads what the previous detective discovered
# 3. Adds its own notes
# 4. Passes the clipboard to the next detective
# ==============================================================================

from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field

# Import our 'Index Card' blueprint from Step 4
from backend.ingestion.models import DocumentChunk


class AgentState(BaseModel):
    """
    The Case File (Shared Notebook):
    Holds all information for an active incident investigation as it moves
    through the LangGraph state machine.
    """

    # 1. The original messy alert or bug report from the user/monitoring system
    # Example: "Checkout throwing 504. Redis memory is critical. Please check."
    incident_report: str = Field(
        description="The incoming problem description or error alert"
    )

    # 2. Sub-queries generated by the Planner Node
    # Example: ["Redis memory exhaustion ERR_OOM", "504 Gateway Timeout checkout"]
    sub_queries: List[str] = Field(
        default_factory=list,
        description="Focused search queries broken down from the main report"
    )

    # 3. The actual cards retrieved by our Hybrid Search + Reranker
    retrieved_docs: List[DocumentChunk] = Field(
        default_factory=list,
        description="The top evidence cards found in our runbooks and logs"
    )

    # 4. Loop Guard: How many times has the agent retried searching?
    # We cap this at 3 so the agent can NEVER get stuck in an infinite loop!
    search_retry_count: int = Field(
        default=0,
        description="Number of times the agent looped back and re-searched"
    )

    # 5. Grader verdict: Is our evidence good enough to solve the incident?
    # Possible values: "pending", "pass", "rewrite_query"
    grader_verdict: str = Field(
        default="pending",
        description="Whether the retrieved evidence is relevant or needs query rewriting"
    )

    # 6. Draft Diagnosis: The AI's first explanation of the root cause and fix
    draft_diagnosis: str = Field(
        default="",
        description="The preliminary diagnosis written by the LLM"
    )

    # 7. Citations: The verified receipts backing up the diagnosis
    # Example: ["[runbook_redis_cluster.md, Section: Mitigation and Recovery Steps]"]
    citations: List[str] = Field(
        default_factory=list,
        description="Exact file and section receipts used in the diagnosis"
    )

    # 8. Safety Gate: Does the agent want to take an external action?
    # Example: Proposing a terminal command or creating a Jira ticket
    requires_approval: bool = Field(
        default=False,
        description="True if the agent wants to perform an action that needs human consent"
    )

    # 9. Human-in-the-Loop Decision: Did the engineer click Approve or Reject?
    # None = waiting for human, True = approved, False = rejected
    human_approved: Optional[bool] = Field(
        default=None,
        description="Human engineer's verdict on the proposed action"
    )

    # 10. Final Output: The verified, audited answer streamed to the user interface
    final_output: str = Field(
        default="",
        description="The final verified response after hallucination auditing"
    )

    # 11. Step-by-step activity trace for the UI live monitor
    step_history: List[str] = Field(
        default_factory=list,
        description="List of steps executed (e.g. ['Planning', 'Searching', 'Grading'])"
    )
